// Helper function to get translation
export function getTranslation(
  namespace: keyof typeof translations,
  key: string,
  language: "en" | "am" | "om" = "en"
): string {
  // Debug: Log available namespaces
  if (typeof window !== "undefined" && process.env.NODE_ENV === "development") {
    const availableNamespaces = Object.keys(translations);
    if (!availableNamespaces.includes(namespace as string)) {
      console.warn(`Translation namespace "${namespace}" not found. Available namespaces:`, availableNamespaces);
    }
  }

  const namespaceTranslations = translations[namespace];
  if (!namespaceTranslations) {
    console.warn(`Translation namespace not found: ${namespace}. Available: ${Object.keys(translations).join(", ")}`);
    return `${namespace}.${key}`;
  }

  const langTranslations = namespaceTranslations[language];
  if (!langTranslations) {
    console.warn(`Language not found: ${language} for namespace: ${namespace}`);
    return `${namespace}.${key}`;
  }

  const translation = langTranslations[key as keyof typeof langTranslations];
  if (!translation) {
    console.warn(`Translation key not found: ${namespace}.${key}. Available keys: ${Object.keys(langTranslations).join(", ")}`);
    return `${namespace}.${key}`;
  }

  return translation;
}

// Hook for using translations in components
export function useTranslation(language: "en" | "am" | "om" = "en") {
  const t = (namespace: keyof typeof translations, key: string): string => {
    return getTranslation(namespace, key, language);
  };

  return { t, language };
}

